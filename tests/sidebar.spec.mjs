import { test, expect } from '@playwright/test';
import { openSidebar, navigate, chooseExercise } from './navigation.mjs';

test('desktop keeps settings in a collapsible sidebar and preserves the exercise',async ({page})=>{
 await page.goto('/');await page.locator('.tab').first().waitFor();
 await expect(page.locator('#app-sidebar')).toBeVisible();
 await expect(page.locator('.workspace-main .sound-settings')).toHaveCount(0);
 await expect(page.locator('.workspace-main .guided-settings')).toHaveCount(0);
 await expect(page.locator('.workspace-main .exercise-menu')).toHaveCount(0);
 await expect(page.locator('.workspace-main .progress')).toHaveCount(0);
 await expect(page.locator('.workspace-main h1')).toBeHidden();
 const title=await page.locator('#title').textContent();
 const card=await page.locator('.card').boundingBox();
 const side=await page.locator('#app-sidebar').boundingBox();
 expect(card.x).toBeGreaterThanOrEqual(side.x+side.width);
 await page.getByRole('button',{name:'Contraer menú lateral',exact:true}).click();
 await expect(page.locator('#app-sidebar')).toBeHidden();
 await expect(page.locator('#title')).toHaveText(title);
 await page.screenshot({path:'/tmp/conservatorio-exercise-desktop.png',fullPage:true});
 await openSidebar(page);
 await page.locator('.sound-settings > summary').click();
 await page.locator('#tempo').fill('112');await page.locator('#tempo').dispatchEvent('change');
 await navigate(page,'Estadísticas');
 await expect(page.locator('#dashboard-page')).toBeVisible();
 await navigate(page,'Práctica');
 await expect(page.locator('#tempo')).toHaveValue('112');
 await expect(page.locator('#title')).toHaveText(title);
 await page.screenshot({path:'/tmp/conservatorio-sidebar-desktop.png',fullPage:true});
});

test('mobile drawer traps focus, closes with Escape and backdrop, and changes views',async ({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.goto('/');await page.locator('.tab').first().waitFor({state:'attached'});
 await expect(page.locator('#app-sidebar')).toBeHidden();
 const card=await page.locator('.card').boundingBox();expect(card.y).toBeLessThan(100);
 await expect(page.locator('.workspace-main .card')).toBeVisible();
 await openSidebar(page);
 await expect(page.getByRole('dialog',{name:'Menú lateral'})).toBeVisible();
 await expect(page.locator('.workspace-main')).toHaveAttribute('inert','');
 await expect(page.locator('.sidebar-close')).toBeFocused();
 await page.keyboard.press('Shift+Tab');
 expect(await page.evaluate(()=>document.getElementById('app-sidebar').contains(document.activeElement))).toBe(true);
 await page.keyboard.press('Escape');
 await expect(page.locator('#app-sidebar')).toBeHidden();
 await expect(page.getByRole('button',{name:'Abrir menú lateral',exact:true})).toBeFocused();
 await openSidebar(page);
 await page.screenshot({path:'/tmp/conservatorio-sidebar-phone.png',fullPage:true});
 await page.locator('.sidebar-backdrop').click({position:{x:385,y:200}});
 await expect(page.locator('#app-sidebar')).toBeHidden();
 await chooseExercise(page,7);
 await expect(page.locator('#title')).toHaveText('Transcripción melódica');
 await expect(page.locator('#app-sidebar')).toBeHidden();
 await navigate(page,'Estadísticas');
 await expect(page.locator('#dashboard-page')).toBeVisible();
 await expect(page.locator('#app-sidebar')).toBeHidden();
 await page.getByRole('button',{name:'Seguir practicando →'}).click();
 await expect(page.locator('#practice-page')).toBeVisible();
 await expect(page.locator('#title')).toHaveText('Transcripción melódica');
 await page.screenshot({path:'/tmp/conservatorio-exercise-phone.png',fullPage:true});
});
