import { selectValue, openSidebar, navigate, chooseExercise } from './navigation.mjs';
import { test, expect } from '@playwright/test';
test('statistics record mistakes, preserve exercises and persist the dark theme',async ({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{Math.random=()=>0;});
 await page.emulateMedia({colorScheme:'light'});
 await page.goto('/');
 await page.locator('.tab').first().waitFor();
 await expect(page.getByText('Tablero de práctica',{exact:true})).toHaveCount(0);
 await navigate(page,'Estadísticas');
 await expect(page.getByRole('heading',{name:'Fallos más comunes'})).toBeVisible();
 await expect(page.locator('.stat-card').first().locator('strong')).toHaveText('0');
 await expect(page.locator('.error-ranking')).toHaveCount(0);
 await page.getByRole('button',{name:'Seguir practicando'}).click();
 await page.locator('#answers button').filter({hasText:'Menor natural'}).click();
 await page.locator('#next').click();
 await expect(page.locator('#feedback')).toContainText('Mayor');
 const question=await page.locator('#feedback').textContent();
 await navigate(page,'Estadísticas');
 await expect(page.locator('.stats-grid .stat-card').first().locator('strong')).toHaveText('1');
 await expect(page.locator('.error-ranking')).toContainText('Menor natural');
 await expect(page.locator('.error-ranking')).toContainText('Mayor');
 await selectValue(page,page.getByRole('combobox',{name:'Ejercicio',exact:true}),'chords');
 await expect(page.locator('.stats-grid .stat-card').first().locator('strong')).toHaveText('0');
 await selectValue(page,page.getByRole('combobox',{name:'Ejercicio',exact:true}),'all');
 await page.getByRole('button',{name:'Activar modo oscuro'}).click();
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:'/tmp/conservatorio-dashboard-dark.png',fullPage:true,animations:'disabled'});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/conservatorio-dashboard-mobile.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await navigate(page,'Práctica');
 await expect(page.locator('#feedback')).toHaveText(question);
 await page.reload();await page.locator('.tab').first().waitFor({state:'attached'});
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await navigate(page,'Estadísticas');
 await expect(page.locator('.stats-grid .stat-card').first().locator('strong')).toHaveText('1');
 await expect(page.locator('.error-ranking')).toContainText('Menor natural');
 await page.locator('.error-ranking').getByRole('button',{name:'Practicar Escalas'}).click();
 await expect(page.locator('#practice-tab')).toHaveAttribute('aria-current','page');
 await expect(page.locator('#title')).toHaveText('Escalas');
 await chooseExercise(page,3);
 await expect(page.locator('#notation svg')).toBeVisible();
 await expect(page.locator('#notation')).toHaveCSS('background-color','rgb(32, 28, 40)');
 await expect(page.locator('#notation svg')).toHaveCSS('color','rgb(237, 232, 243)');
 await page.locator('#notation').screenshot({path:'/tmp/conservatorio-staff-dark.png',animations:'disabled'});
 expect(errors).toEqual([]);
});
